import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent
CLAUDE_RULES_DIR = _ROOT / ".claude" / "rules"
CURSOR_RULES_DIR = _ROOT / ".cursor" / "rules"
SUMMARY_NAME = "claude-rules.mdc"
STUB_PREFIX = "claude-rule-"


def _parse_rule(text: str) -> tuple[list[str], str]:
    """Split a .claude/rules file into its `paths:` globs and first heading.
    param text(str): rule file contents
    return(tuple[list[str], str]): globs (empty for always-on rules), heading
    """
    paths: list[str] = []
    body = text
    if text.startswith("---\n"):
        frontmatter, body = text[4:].split("\n---\n", 1)
        paths = [
            line.strip().removeprefix("- ").strip('"')
            for line in frontmatter.splitlines()
            if line.startswith("  - ")
        ]
    heading = next(line[2:] for line in body.splitlines() if line.startswith("# "))
    return paths, heading


def expected_stubs(rules_dir: Path) -> dict[str, str]:
    """Render one glob-scoped Cursor rule per path-scoped .claude/rules file.
    param rules_dir(Path): .claude/rules directory
    return(dict[str, str]): stub filename -> contents
    """
    stubs = {}
    for rule in sorted(rules_dir.glob("*.md")):
        paths, heading = _parse_rule(rule.read_text())
        if not paths:
            continue
        source = f".claude/rules/{rule.name}"
        stubs[f"{STUB_PREFIX}{rule.stem}.mdc"] = (
            f"---\ndescription: {heading}\nglobs: {', '.join(paths)}\nalwaysApply: false\n---\n\n"
            f"Read `{source}` and follow it. Generated by `make cursor-rules`; edit the source, not this file.\n"
        )
    return stubs


def find_problems(rules_dir: Path, cursor_dir: Path) -> list[str]:
    """List drift between .claude/rules and the Cursor rules that mirror it.
    param rules_dir(Path): .claude/rules directory
    param cursor_dir(Path): .cursor/rules directory
    return(list[str]): one line per problem; empty when in sync
    """
    expected = expected_stubs(rules_dir)
    actual = {p.name: p.read_text() for p in cursor_dir.glob(f"{STUB_PREFIX}*.mdc")}
    problems = [f"missing: {n}" for n in expected if n not in actual]
    problems += [f"stale: {n}" for n in expected if n in actual and actual[n] != expected[n]]
    problems += [f"orphan: {n}" for n in actual if n not in expected]
    summary = (cursor_dir / SUMMARY_NAME).read_text()
    for rule in sorted(rules_dir.glob("*.md")):
        if not _parse_rule(rule.read_text())[0] and rule.name not in summary:
            problems.append(f"not in {SUMMARY_NAME}: {rule.name}")
    return problems


def write_stubs(rules_dir: Path, cursor_dir: Path) -> None:
    """Regenerate the glob-scoped stubs and delete ones whose source rule is gone.
    param rules_dir(Path): .claude/rules directory
    param cursor_dir(Path): .cursor/rules directory
    """
    expected = expected_stubs(rules_dir)
    for stale in cursor_dir.glob(f"{STUB_PREFIX}*.mdc"):
        if stale.name not in expected:
            stale.unlink()
    for name, contents in expected.items():
        (cursor_dir / name).write_text(contents)


if __name__ == "__main__":
    if "--check" not in sys.argv:
        write_stubs(CLAUDE_RULES_DIR, CURSOR_RULES_DIR)
        sys.exit(0)
    problems = find_problems(CLAUDE_RULES_DIR, CURSOR_RULES_DIR)
    for problem in problems:
        print(f".cursor/rules out of sync with .claude/rules — {problem} (run `make cursor-rules`)")
    sys.exit(1 if problems else 0)
