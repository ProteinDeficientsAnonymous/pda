#!/usr/bin/env python3
"""Run diff-scoped mutation testing on changed backend Python files; report survivors."""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
BACKEND = REPO_ROOT / "backend"
UV_WITH_MUTMUT = ["uv", "run", "--with", "mutmut==3.8.1"]
MUTMUT = [*UV_WITH_MUTMUT, "mutmut"]
# mutated modules import mutmut's trampoline, so the rerun needs it installed too
PYTEST = [*UV_WITH_MUTMUT, "python", "-m", "pytest", "--rootdir=.", "-x", "-q", "--tb=short"]
CONFIG = BACKEND / "setup.cfg"
CONFIG_MARKER = "# generated by scripts/run_mutation.py"
NOT_SOURCE = frozenset({"tests", "mutants"})
MAX_SHOWN = 20
BASELINE_TAIL = 60
# a fixed seed keeps survivor counts stable across runs of the Hypothesis tests
PYTEST_ARGS = ["-o", "addopts=", "-p", "no:cacheprovider", "--hypothesis-seed=0"]
FULL_SUITE_SKIP = (
    "### Mutation testing: skipped\n"
    "This diff maps to the full test suite (a migration, shared config, or a backend path "
    "`scripts/list_affected_tests.py` has no bundle for). mutmut would run all of `tests/` "
    "serially as its baseline, which does not fit this job. Map the path to a bundle, or run "
    "`python3 scripts/run_mutation.py <files> --tests <tests>` locally."
)
SCOPE_NOTE = "mutmut 3 skips decorated functions (ninja endpoints, `@property`, validators); those are not covered."


class MutmutFailed(Exception):
    def __init__(self, message: str, output: str = "") -> None:
        super().__init__(message)
        self.output = output


def changed_backend_files(base: str) -> list[str]:
    out = subprocess.check_output(
        ["git", "diff", "--name-only", "--diff-filter=AM", f"{base}...HEAD", "--", "backend/"],
        cwd=REPO_ROOT,
        text=True,
    )
    return [
        raw.removeprefix("backend/")
        for raw in out.splitlines()
        if raw.endswith(".py") and "/tests/" not in raw and "/migrations/" not in raw
    ]


def affected_tests(base: str) -> list[str] | None:
    """return(list | None): pytest paths for the diff; None when it needs the full suite."""
    out = subprocess.check_output(
        [sys.executable, str(REPO_ROOT / "scripts" / "list_affected_tests.py"), "--base", base],
        cwd=REPO_ROOT,
        text=True,
    )
    paths = [line for line in out.splitlines() if line.strip()]
    return None if not paths or "__FULL__" in paths else paths


def source_packages(backend: Path) -> list[str]:
    return sorted(
        f"{p.name}/"
        for p in backend.iterdir()
        if p.is_dir() and p.name not in NOT_SOURCE and (p / "__init__.py").is_file()
    )


def render_config(backend: Path, targets: list[str], tests: list[str]) -> str:
    """mutmut 3 reads its options only from setup.cfg/pyproject.toml in its working directory."""
    also_copy = ["templates/", "manage.py", *sorted(p.name for p in backend.glob("*.json"))]

    def block(key: str, values: list[str]) -> str:
        return f"{key}=\n" + "".join(f"    {v}\n" for v in values)

    return "".join(
        [
            f"{CONFIG_MARKER}\n[mutmut]\n",
            # plain fork hands every worker the parent's open Postgres connection, and they hang
            "process_isolation=forkserver\n",
            # its forkserver logger otherwise writes to a closed stream and floods the output
            "log_to_file=true\n",
            block("source_paths", source_packages(backend)),
            block("only_mutate", targets),
            block("also_copy", also_copy),
            block("pytest_add_cli_args", PYTEST_ARGS),
            block("pytest_add_cli_args_test_selection", tests),
        ]
    )


def survivor_ids(results_text: str) -> list[str]:
    """param(str): `mutmut results` output. return(list): names of surviving mutants."""
    return [
        line.strip().removesuffix(": survived")
        for line in results_text.splitlines()
        if line.strip().endswith(": survived")
    ]


def _mutmut(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [*MUTMUT, *args], cwd=BACKEND, capture_output=True, text=True, check=False
    )


def baseline_tail(tests: list[str]) -> str:
    """Rerun the unmutated tests in mutants/: mutmut runs its baseline in a forked child and drops the output."""
    mutants = BACKEND / "mutants"
    if not mutants.is_dir():
        return ""
    proc = subprocess.run(
        [*PYTEST, *PYTEST_ARGS, *tests],
        cwd=mutants,
        env={**os.environ, "MUTANT_UNDER_TEST": ""},
        capture_output=True,
        text=True,
        check=False,
    )
    return "\n".join(((proc.stdout or "") + (proc.stderr or "")).splitlines()[-BASELINE_TAIL:])


def report(survivors: list[str], diffs: dict[str, str]) -> str:
    lines = [f"### Mutation testing: {len(survivors)} surviving mutant(s)", ""]
    for mutant in survivors[:MAX_SHOWN]:
        lines += [f"`{mutant}`", "```diff", diffs.get(mutant, ""), "```"]
    if len(survivors) > MAX_SHOWN:
        lines.append(f"…and {len(survivors) - MAX_SHOWN} more (`mutmut results`).")
    lines.append(
        "Each survivor is a change to the code that no test noticed: add or tighten a test."
    )
    lines.append(SCOPE_NOTE)
    return "\n".join(lines)


def run_mutmut(targets: list[str], tests: list[str]) -> tuple[list[str], dict[str, str]]:
    """return(tuple): (surviving mutant names, diffs of the first MAX_SHOWN of them)."""
    if CONFIG.exists() and not CONFIG.read_text().startswith(CONFIG_MARKER):
        raise SystemExit(f"{CONFIG} exists and was not generated by this script; not overwriting")
    # a previous run's mutants/ would report survivors for other files
    shutil.rmtree(BACKEND / "mutants", ignore_errors=True)
    CONFIG.write_text(render_config(BACKEND, targets, tests))
    try:
        # mutmut exits 0 with survivors; non-zero means its clean baseline run or setup broke
        run = subprocess.run([*MUTMUT, "run"], cwd=BACKEND, check=False)
        if run.returncode != 0:
            raise MutmutFailed(f"mutmut run exited {run.returncode}", baseline_tail(tests))
        survivors = survivor_ids(_mutmut("results").stdout)
        # `mutmut show` needs the config too, so collect diffs before it is removed
        diffs = {m: _mutmut("show", m).stdout.strip() for m in survivors[:MAX_SHOWN]}
        return survivors, diffs
    finally:
        CONFIG.unlink(missing_ok=True)
        shutil.rmtree(BACKEND / "mutants", ignore_errors=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "paths", nargs="*", help="backend-relative files to mutate (default: changed files)"
    )
    parser.add_argument("--base", default=os.environ.get("DIFF_COVER_BASE", "origin/main"))
    parser.add_argument(
        "--tests", nargs="+", help="backend-relative pytest paths (default: affected by the diff)"
    )
    parser.add_argument(
        "--enforce", action="store_true", help="exit non-zero when any mutant survives"
    )
    args = parser.parse_args(argv)
    targets = args.paths or changed_backend_files(args.base)
    if not targets:
        print("No changed backend domain files to mutate.")
        return 0
    tests = args.tests or affected_tests(args.base)
    if tests is None:
        _write(FULL_SUITE_SKIP)
        return 0
    print("Mutating:", ", ".join(targets), "| tests:", " ".join(tests), flush=True)
    try:
        survivors, diffs = run_mutmut(targets, tests)
    except MutmutFailed as exc:
        text = f"### Mutation testing: could not run\n{exc}. No mutants were tested."
        if exc.output:
            text += f"\nThe unmutated baseline, rerun (last {BASELINE_TAIL} lines):\n```\n{exc.output}\n```"
        _write(text)
        if os.environ.get("GITHUB_ACTIONS") == "true":
            print(f"::error::mutation testing could not run: {exc}")
        return 1
    _write(
        report(survivors, diffs)
        if survivors
        else f"### Mutation testing: no surviving mutants\n{SCOPE_NOTE}"
    )
    return 1 if survivors and args.enforce else 0


def _write(text: str) -> None:
    print(text)
    if summary := os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(summary, "a", encoding="utf-8") as fh:
            fh.write(text + "\n")


if __name__ == "__main__":
    sys.exit(main())
